      break;

    case DISPLAY_LOGMSG_SELFCHECK_FAIL:
      cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_ZI_SELF, color));
      cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_JIAN, color));
