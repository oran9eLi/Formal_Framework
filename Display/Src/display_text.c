/* Draw one glyph, return advance width in pixels. */
static uint16_t Display_TextDrawGlyph(uint16_t x, uint16_t y,
                                      Display_MsgGlyph_t g, uint16_t color)
{
  (void)Display_TextDrawBitmap(x, y, &s_mlg_table[g], color);
  return s_mlg_table[g].width;
}

/* Draw a single ASCII digit (scale 2) aligned with the 16px glyph row. */
static uint16_t Display_TextDrawDigit(uint16_t x, uint16_t y, char d, uint16_t color)
{
  char s[2];

  s[0] = d;
  s[1] = '\0';
  (void)Display_GfxDrawString(x, (uint16_t)(y + 1U), s, color, 2U);
  return 12U;
}

/* Draw a numbered-motor fault: "<n> hao dian ji gu zhang". */
static uint16_t Display_TextDrawMotorFault(uint16_t x, uint16_t y,
                                           char index, uint16_t color)
{
  uint16_t cx = x;

  cx = (uint16_t)(cx + Display_TextDrawDigit(cx, y, index, color));
  cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_HAO, color));
  cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_DIAN, color));
  cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_JI, color));
  cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_GU, color));
  cx = (uint16_t)(cx + Display_TextDrawGlyph(cx, y, MLG_ZHANG, color));
  return (uint16_t)(cx - x);
}

