/** @brief 返回与原生短边限制相同的固定半径描述符；无匹配时不占用任何资源。 */
static _lv_draw_mask_radius_circle_dsc_t *HudMask_Find(lv_coord_t radius)
{
  uint8_t i;
  for(i=0U;i<5U;i++) { if(s_hud_circles[i].radius==radius) { return &s_hud_circles[i]; } }
  return 0;
}

/** @brief 半径为0的原生初始化仅设置回调和矩形，不分配AA表；随后绑定固定Flash数据。 */
void Display_HudMaskRadiusInit(lv_draw_mask_radius_param_t *param,const lv_area_t *rect,lv_coord_t radius,bool inv)
{
  _lv_draw_mask_radius_circle_dsc_t *circle;
  lv_coord_t limit=(lv_coord_t)(LV_MIN(lv_area_get_width(rect),lv_area_get_height(rect))/2);
  if(radius>limit) { radius=limit; }
  if(radius<0) { radius=0; }
  circle=HudMask_Find(radius);
  if(!circle) { lv_draw_mask_radius_init(param,rect,radius,inv);return; }
  lv_draw_mask_radius_init(param,rect,0,inv);
  param->cfg.radius=radius;param->circle=circle;
}

/** @brief 自有表不进入原生free；其他半径保留原生引用计数/释放规则。 */
void Display_HudMaskRadiusFree(lv_draw_mask_radius_param_t *param)
{
  uint8_t i;
  if(!param) { return; }
  for(i=0U;i<5U;i++) { if(param->circle==&s_hud_circles[i]) { return; } }
  lv_draw_mask_free_param(param);
}

/** @brief 用预备双外mask复现原生完整环中arc外mask与圆角rect外mask的重复抗锯齿。 */
void Display_HudDrawFullRing(lv_draw_ctx_t *dc,const lv_draw_arc_dsc_t *dsc,const lv_point_t *center,uint16_t radius)
{
  lv_area_t outer,inner;
  lv_draw_rect_dsc_t rect;
  lv_draw_mask_radius_param_t mi,mo,mr;
  int16_t ii,io,ir;
  if(dsc->img_src || !((radius==104U && dsc->width==2) || (radius==115U && dsc->width==22))) {
    lv_draw_arc(dc,dsc,center,radius,0,360);return;
  }
  if(dsc->opa<=LV_OPA_MIN) { return; }
  outer.x1=(lv_coord_t)(center->x-radius);outer.y1=(lv_coord_t)(center->y-radius);
  outer.x2=(lv_coord_t)(center->x+radius-1);outer.y2=(lv_coord_t)(center->y+radius-1);
  inner=outer;
  inner.x1=(lv_coord_t)(inner.x1+dsc->width);inner.y1=(lv_coord_t)(inner.y1+dsc->width);
  inner.x2=(lv_coord_t)(inner.x2-dsc->width);inner.y2=(lv_coord_t)(inner.y2-dsc->width);
  Display_HudMaskRadiusInit(&mi,&inner,LV_RADIUS_CIRCLE,true);ii=lv_draw_mask_add(&mi,0);
  Display_HudMaskRadiusInit(&mo,&outer,LV_RADIUS_CIRCLE,false);io=lv_draw_mask_add(&mo,0);
  Display_HudMaskRadiusInit(&mr,&outer,LV_RADIUS_CIRCLE,false);ir=lv_draw_mask_add(&mr,0);
  lv_draw_rect_dsc_init(&rect);rect.bg_opa=dsc->opa;rect.bg_color=dsc->color;rect.blend_mode=dsc->blend_mode;
  rect.radius=0;
  lv_draw_rect(dc,&rect,&outer);
  lv_draw_mask_remove_id(ir);lv_draw_mask_remove_id(io);lv_draw_mask_remove_id(ii);
  Display_HudMaskRadiusFree(&mr);Display_HudMaskRadiusFree(&mo);Display_HudMaskRadiusFree(&mi);
}

